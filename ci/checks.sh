#!/usr/bin/env bash
# The checks of CI, run inside the dev container by ci/run.sh, or as they
# are on a machine with the tools, as CI does. Given names, only those run:
# ci/run.sh check clippy vale
set -euo pipefail
cd "$(dirname "$0")/.."

crates=(-p rookery-api -p rookery-pty -p rookery-core -p rookery-setup -p rookery -p rookeryd -p box
  -p rookery-proto -p rookery-store -p rookery-kernel -p rookery-auth -p rookery-server
  -p rookery-facilities -p rookery-jobs -p rookery-hosts -p rookery-client -p rookery-plugins
  -p rookery-filter -p rookery-data -p rookery-documents)

# Each runs as the condition of an if, where set -e does not stop it: the
# steps are joined with && instead.
# nextest runs the test programs side by side, which pays on a machine with
# many cores. On CI's four it is slower than cargo test.
# The tests of rookery serve make a database each on the Postgres of
# ROOKERY_TEST_POSTGRES. The TypeScript types of the wire are compared with
# client/src/generated, with the feature that writes them.
rust-tests() {
  if cargo nextest --version >/dev/null 2>&1; then
    cargo nextest run --locked --no-fail-fast
  elif [ -n "${CI:-}" ]; then
    # Without nextest a test that hangs holds the job until its timeout.
    echo "CI runs the Rust tests with cargo-nextest, which is not installed" >&2
    false
  else
    cargo test --locked --no-fail-fast
  fi && cargo test --locked -q -p rookery-proto --features ts --test bindings
}
# Each file in a process of its own, side by side, its output when it is done.
python-tests() {
  local file out=build/python-tests pids=() bad=0
  rm -rf "$out" && mkdir -p "$out"
  for file in tests/test_*.py; do
    file=$(basename "$file")
    python3 -m unittest discover -s tests -p "$file" -v >"$out/$file.log" 2>&1 &
    pids+=("$!:$file")
  done
  for entry in "${pids[@]}"; do
    if wait "${entry%%:*}"; then
      grep -E '^(Ran|OK)' "$out/${entry#*:}.log" | paste -sd ' ' | sed "s|^|${entry#*:}: |"
    else
      cat "$out/${entry#*:}.log"
      echo "${entry#*:} failed" >&2
      bad=1
    fi
  done
  return "$bad"
}
shell-syntax() {
  local script bad=0
  for script in install.sh provision/bin/*.sh provision/bootstrap/*.sh container/*.sh ci/*.sh \
    provision/ansible/roles/rookery/files/*.sh provision/ansible/roles/rookery/files/tasks/*.sh plugins/rookery/*/rookery/files/*.sh \
    recipes/*/*.sh; do
    bash -n "$script" || bad=1
  done
  return "$bad"
}
ansible-syntax() {
  (cd provision && ansible-playbook -i localhost, ansible/site.yml --syntax-check) &&
    (cd provision && ansible-playbook -i localhost, ansible/controller.yml --syntax-check) &&
    (cd recipes/rookery-server && ansible-playbook -i localhost, site.yml --syntax-check)
}
fmt() { cargo fmt --check "${crates[@]}"; }
# Every package of the registry of the plugins that come with Rookery keeps the plugin contract.
plugin-check() { cargo run --locked -q -p rookery -- plugin check plugins; }
clippy() { cargo clippy --locked --all-targets -- -D warnings; }
# The API pages under docs/content/docs/api are generated by the docs build and not committed.
vale() {
  command vale --minAlertLevel=warning --glob='!docs/content/docs/api/{host,server}/**' \
    README.md AGENTS.md docs/AGENTS.md docs/content/docs plugins/rookery/*/rookery/guide.md
}

all=(fmt shell-syntax ansible-syntax vale python-tests rust-tests plugin-check clippy)
if (($#)); then steps=("$@"); else steps=("${all[@]}"); fi
for step in "${steps[@]}"; do
  if [[ " ${all[*]} " != *" $step "* ]]; then
    echo "No check $step. The checks: ${all[*]}" >&2
    exit 2
  fi
done

# GitHub folds the output of each check.
group() { [[ -n ${GITHUB_ACTIONS:-} ]] && echo "::group::$1"; true; }
endgroup() { [[ -n ${GITHUB_ACTIONS:-} ]] && echo "::endgroup::"; true; }

failed=()
for step in "${steps[@]}"; do
  group "$step"
  start=$SECONDS
  if "$step"; then
    endgroup
    echo "== $step passed ($((SECONDS - start))s)"
  else
    endgroup
    echo "== $step failed ($((SECONDS - start))s)"
    failed+=("$step")
  fi
done
if ((${#failed[@]})); then
  echo "Failed: ${failed[*]}" >&2
  exit 1
fi
